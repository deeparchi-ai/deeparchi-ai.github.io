// Chinese is the default; English uses a local, explicit dictionary.
export function translator(language = 'zh-CN') {
  return (message, values = {}) => {
    const text = language === 'en' ? EN[message] : message;
    if (text === undefined) throw new Error(`Missing English message: ${message}`);
    return text.replace(/\{(\w+)\}/g, (_, key) => values[key] ?? `{${key}}`);
  };
}

export function analyticsStatus(status, t) {
  const prefix = '内部测试 / 本地预览：不会真实上报。';
  return status.startsWith(prefix) ? t(prefix) + t(status.slice(prefix.length)) : t(status);
}

